# shellcheck shell=bash
# Host-only steps (Fedora Workstation / GNOME).

HOST_DIR="$DOTFILES_DIR/host"

host_repos() {
	section "Repositories"
	if ! is_fedora; then
		warn "Not Fedora: skipping RPM Fusion / COPR / Google Chrome repos"
		return 0
	fi
	local rel
	rel="$(rpm -E %fedora)"
	if ! rpm -q rpmfusion-free-release rpmfusion-nonfree-release >/dev/null 2>&1; then
		log "Adding RPM Fusion free + nonfree"
		as_root dnf install -y \
			"https://mirrors.rpmfusion.org/free/fedora/rpmfusion-free-release-${rel}.noarch.rpm" \
			"https://mirrors.rpmfusion.org/nonfree/fedora/rpmfusion-nonfree-release-${rel}.noarch.rpm"
	fi
	if ! dnf config-manager --help >/dev/null 2>&1; then
		as_root dnf install -y dnf5-plugins || as_root dnf install -y dnf-plugins-core
	fi
	as_root dnf config-manager setopt fedora-cisco-openh264.enabled=1
	# Google Chrome repo ships with fedora-workstation-repositories (disabled by default).
	as_root dnf install -y fedora-workstation-repositories
	as_root dnf config-manager setopt google-chrome.enabled=1
	fedora_enable_lazygit_copr
}

host_packages() {
	section "Packages"
	pkg_upgrade
	pkg_install_lists "$DOTFILES_DIR/packages/base.txt" "$HOST_DIR/packages.txt"
	have lazygit || install_lazygit_binary
}

host_flatpaks() {
	section "Flatpaks"
	have flatpak || pkg_install flatpak
	# System-wide Flathub remote (Fedora may ship it disabled).
	as_root flatpak remote-add --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo
	as_root flatpak remote-modify --enable flathub 2>/dev/null || true
	local apps=()
	mapfile -t apps < <(sed -e 's/#.*//' -e '/^[[:space:]]*$/d' -e 's/[[:space:]]//g' "$HOST_DIR/flatpaks.txt")
	log "Updating installed flatpaks"
	flatpak update -y --noninteractive
	if ((${#apps[@]})); then
		log "Installing ${#apps[@]} flatpak(s)"
		flatpak install -y --noninteractive flathub "${apps[@]}"
	fi
	ok "Flatpaks done"
}

# ------------------------------------------------------------------ GNOME ---
# host/dconf-paths.txt lists what is tracked:
#   /some/dir/   -> the whole directory (recursive) is dumped
#   /some/key    -> just that key
_dconf_paths() {
	sed -e 's/#.*//' -e '/^[[:space:]]*$/d' -e 's/[[:space:]]//g' "$HOST_DIR/dconf-paths.txt"
}

gnome_dump() {
	have dconf || die "dconf not found (this is meant to run on the GNOME host)"
	local out="$HOST_DIR/dconf.ini" tmp p dir key
	tmp="$(mktemp)"
	{
		echo "# Generated by 'dotfiles gnome dump'. Restore with 'dotfiles gnome restore'."
		echo "# Tracked paths are listed in host/dconf-paths.txt."
		while IFS= read -r p; do
			if [[ "$p" == */ ]]; then
				dir="${p#/}"
				dir="${dir%/}"
				# dconf dump prints sections relative to the dumped dir: make them absolute.
				dconf dump "$p" | awk -v base="$dir" '
					/^\[\/\]$/ { print ""; print "[" base "]"; next }
					/^\[.*\]$/ { sub(/^\[/, ""); sub(/\]$/, ""); print ""; print "[" base "/" $0 "]"; next }
					/^$/ { next }
					{ print }'
			else
				dir="${p%/*}"
				dir="${dir#/}"
				key="${p##*/}"
				local val
				val="$(dconf read "$p")"
				[[ -n "$val" ]] || continue
				printf '\n[%s]\n%s=%s\n' "$dir" "$key" "$val"
			fi
		done < <(_dconf_paths)
	} >"$tmp"
	mv "$tmp" "$out"
	ok "Saved GNOME settings to $out"
}

gnome_restore() {
	section "GNOME settings"
	have dconf || {
		warn "dconf not found: skipping"
		return 0
	}
	# 'dconf load /' only writes the keys present in the file.
	grep -v '^#' "$HOST_DIR/dconf.ini" | dconf load /
	ok "GNOME settings restored from host/dconf.ini"
}

gnome_extensions() {
	section "GNOME extensions"
	have gnome-browser-connector || pkg_install gnome-browser-connector
	local args=() ext
	while IFS= read -r ext; do
		args+=("gnome-extensions://${ext//@/%40}/?action=install")
	done < <(sed -e 's/#.*//' -e '/^[[:space:]]*$/d' -e 's/[[:space:]]//g' "$HOST_DIR/gnome-extensions.txt")
	((${#args[@]})) || return 0
	log "Installing ${#args[@]} extension(s): GNOME will ask for confirmation for each one"
	gnome-browser-connector "${args[@]}" || die "Extension installation failed"
	ok "Extensions installed"
}

host_set_shell() {
	section "Login shell"
	local zsh
	zsh="$(command -v zsh)" || {
		warn "zsh not installed"
		return 0
	}
	if [[ "$(getent passwd "$USER" | cut -d: -f7)" != "$zsh" ]]; then
		# sudo so that chsh does not prompt for the user password
		as_root chsh -s "$zsh" "$USER"
		ok "Login shell set to $zsh (log out and back in)"
	fi
}

# --------------------------------------------------------------- distrobox ---
DISTROBOX_INI="$DOTFILES_DIR/distrobox/distrobox.ini"
FEDORA_BASE_IMAGE="localhost/dotfiles-fedora:latest"

# Box sections in distrobox.ini (sections starting with '_' are templates).
boxes_list() {
	sed -n 's/^\[\([^]_][^]]*\)\]\s*$/\1/p' "$DISTROBOX_INI"
}

# shellcheck disable=SC2120
boxes_build() {
	section "Building Fedora base image ($FEDORA_BASE_IMAGE)"
	have podman || die "podman is not installed (run: dotfiles host distrobox)"
	podman build "$@" -t "$FEDORA_BASE_IMAGE" \
		-f "$DOTFILES_DIR/distrobox/Containerfile.fedora" \
		"$DOTFILES_DIR"
	ok "Built $FEDORA_BASE_IMAGE"
}

host_distrobox_install() {
	section "Distrobox"
	have podman || pkg_install podman
	have distrobox || pkg_install distrobox
	mkdir -p "$HOME/distrobox-homes" "$HOME/.local/bin"
}

# boxes_assemble <create|replace> [names...]
boxes_assemble() {
	local mode="$1"
	shift
	have distrobox || die "distrobox is not installed (run: dotfiles host distrobox)"
	[[ -d "$HOME/.ssh" ]] || die "$HOME/.ssh directory does not exist (needed for /etc/host-ssh mount)."
	mkdir -p "$HOME/distrobox-homes" "$HOME/.local/bin"
	if have podman && ! podman image exists "$FEDORA_BASE_IMAGE" 2>/dev/null; then
		log "Base image $FEDORA_BASE_IMAGE not found locally. Building it first..."
		boxes_build
	fi
	local names=("$@") n
	((${#names[@]})) || mapfile -t names < <(boxes_list)
	for n in "${names[@]}"; do
		boxes_list | grep -qx "$n" || die "No box named '$n' in $DISTROBOX_INI"
		if [[ "$mode" == replace ]]; then
			log "Recreating $n (its home in ~/distrobox-homes/$n is kept)"
			distrobox assemble create --replace --file "$DISTROBOX_INI" --name "$n"
		elif distrobox list --no-color 2>/dev/null | awk -F'|' '{gsub(/ /,"",$2); print $2}' | grep -qx "$n"; then
			log "$n already exists, skipping (use 'dotfiles boxes replace $n')"
		else
			log "Creating $n"
			distrobox assemble create --file "$DISTROBOX_INI" --name "$n"
		fi
	done
}
